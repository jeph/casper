import AppKit
import ApplicationServices
import Carbon.HIToolbox
import OSLog

/// Types text at the cursor in the frontmost app by pasting it, then puts back what was on the clipboard.
///
/// Pasting works in nearly every app, including browsers, Electron apps and terminals. Sending ⌘V needs
/// Accessibility permission; without it, the text is left on the clipboard for the user to paste.
@MainActor
enum TextInserter {
  private static let logger = Logger(subsystem: "io.jeph.Casper", category: "TextInserter")

  /// How long the frontmost app gets to read the clipboard after ⌘V before it's restored.
  private static let restoreDelay = Duration.seconds(1)

  /// Markers from nspasteboard.org that tell clipboard managers not to record the dictated text.
  private static let clipboardManagerMarkers = [
    NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
  ]

  /// The clipboard as it was before the first of any pastes still waiting for their restore.
  private static var savedItems: [NSPasteboardItem] = []
  /// The clipboard's change count right after the paste waiting for its restore, or `nil` if none is waiting.
  private static var pendingRestoreChangeCount: Int?
  private static var restoreTask: Task<Void, Never>?

  static func insert(_ text: String) {
    let pasteboard = NSPasteboard.general
    // A paste that starts before the previous one is restored keeps the clipboard saved by the previous one, unless
    // the user copied something since, which then becomes the clipboard to restore.
    if pasteboard.changeCount != pendingRestoreChangeCount {
      savedItems = copies(of: pasteboard.pasteboardItems ?? [])
    }
    restoreTask?.cancel()
    restoreTask = nil
    pendingRestoreChangeCount = nil

    let item = NSPasteboardItem()
    item.setString(text, forType: .string)
    for marker in clipboardManagerMarkers {
      item.setData(Data(), forType: marker)
    }
    pasteboard.clearContents()
    pasteboard.writeObjects([item])

    guard AXIsProcessTrusted() else {
      logger.error("Accessibility access is off, so the dictated text was left on the clipboard.")
      savedItems = []
      return
    }
    postCommandV()

    let changeCount = pasteboard.changeCount
    pendingRestoreChangeCount = changeCount
    restoreTask = Task {
      do {
        try await Task.sleep(for: restoreDelay)
      } catch {
        return
      }
      restoreTask = nil
      pendingRestoreChangeCount = nil
      // Leave the clipboard alone if something else was copied in the meantime.
      if pasteboard.changeCount == changeCount {
        pasteboard.clearContents()
        pasteboard.writeObjects(savedItems)
      }
      savedItems = []
    }
  }

  private static func copies(of items: [NSPasteboardItem]) -> [NSPasteboardItem] {
    items.map { item in
      let copy = NSPasteboardItem()
      for type in item.types {
        if let data = item.data(forType: type) {
          copy.setData(data, forType: type)
        }
      }
      return copy
    }
  }

  private static func postCommandV() {
    let keyCode = pasteKeyCode()
    let source = CGEventSource(stateID: .combinedSessionState)
    for isKeyDown in [true, false] {
      let event = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: isKeyDown)
      // Setting the flags replaces any modifiers the user is still holding from the dictation hotkey.
      event?.flags = .maskCommand
      event?.post(tap: .cghidEventTap)
    }
  }

  /// The key that types "v" while Command is held, which isn't the QWERTY V key in layouts such as Dvorak.
  private static func pasteKeyCode() -> CGKeyCode {
    (0..<128).map(CGKeyCode.init).first { Hotkey.characterInCurrentLayout($0, carbonModifiers: cmdKey) == "v" }
      ?? CGKeyCode(kVK_ANSI_V)
  }
}
